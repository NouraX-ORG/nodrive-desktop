def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if a run would change files")
    ap.add_argument("-v", "--verbose", action="store_true", help="list every change")
    ap.add_argument("--root", default=str(ROOT), help="repository root (default: this checkout)")
    args = ap.parse_args()

    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    ctx = Context(Path(args.root), check=args.check, verbose=args.verbose)
    try:
        for step in STEPS:
            step(ctx)
        plugins = run_plugins(ctx)
    except RebrandError as e:
        print(f"rebrand: ERROR: {e}", file=sys.stderr)
        return 2
    ctx.flush()

    files = sorted({rel for rel, _ in ctx.changes})
    verb = "would change" if args.check else "changed"
    if files and not args.verbose:
        for rel in files:
            print(f"  {verb}: {rel}")
    print(f"rebrand: {len(ctx.changes)} change(s) in {len(files)} file(s) {verb}; plugins: {', '.join(plugins) or 'none'}")
    if args.check and files:
        print("rebrand: the tree is not fully rebranded - run python tools/rebrand.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
