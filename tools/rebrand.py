def run_plugins(ctx: Context) -> list[str]:
    ran = []
    for p in sorted((ctx.root / "tools" / "rebrand.d").glob("*.py")):
        spec = importlib.util.spec_from_file_location(f"rebrand_plugin_{p.stem}", p)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        if not hasattr(mod, "apply") or not hasattr(mod, "LANE"):
            raise RebrandError(f"{p.name}: a plugin needs LANE and apply(ctx)")
        ctx.lane = mod.LANE
        mod.apply(ctx)
        ctx.lane = "shared"
        ran.append(p.name)
    return ran


