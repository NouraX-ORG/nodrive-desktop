_CJK = re.compile("[\u3000-\u30ff\u3400-\u9fff\uac00-\ud7af\uff00-\uffef]")


def _strip_nextcloud(raw: str) -> str:
    """Remove the word Nextcloud (and the space or hyphen that joins it)."""

    def repl(m: re.Match) -> str:
        before, hyphen, after = m.group("b") or "", m.group("h"), m.group("a") or ""
        if hyphen:
            return before + after
        if before and after:
            left = m.string[m.start() - 1] if m.start() > 0 else ""
            right = m.string[m.end()] if m.end() < len(m.string) else ""
            # no space between CJK characters; otherwise keep one space
            return "" if (_CJK.match(left or " ") and _CJK.match(right or " ")) else " "
        return ""

    # an inflection that follows (Nextcloudi, Nextcloud's) belongs to the word
    return re.sub("(?P<b>[ \u00a0]?)nextcloud[a-zA-Z\u00c0-\u024f\u0400-\u04ff'\u2019]*(?:(?P<h>[-\u2010\u2011])|(?P<a>[ \u00a0]?))", repl, raw, flags=re.I)


def _strip_links(raw: str) -> str:
    out = re.sub(r"&lt;a\b.*?&gt;", "", raw, flags=re.S)
    return out.replace("&lt;/a&gt;", "")


# (context, old source as written in the .ts (XML-escaped), new source or None, action)
TS_RULES = [
    ("AssistantMessageList", "Start a conversation with Nextcloud Assistant.",
     "Start a conversation with the Assistant.", _strip_nextcloud),
    # Stale entry: src/gui/AssistantWindow.qml no longer exists and the code says "Assistant".
    ("AssistantWindow", "Nextcloud Assistant", None, "drop"),
    ("OCC::AdvancedSettings",
     "seconds (if &lt;a href=&quot;https://github.com/nextcloud/notify_push&quot;&gt;Client Push&lt;/a&gt; is unavailable)",
     "seconds (if Client Push is unavailable)", _strip_links),
    # OCC::LegalNotice copyright line: legal text, kept unchanged (dialog is not reachable, NOTICE.md).
]

_CONTEXT_RE = re.compile(r"<context>\s*<name>(?P<name>.*?)</name>(?P<body>.*?)</context>", re.S)
_MESSAGE_RE = re.compile(r"(?P<indent>[ \t]*)<message(?P<attrs>[^>]*)>(?P<body>.*?)</message>[ \t]*\r?\n?", re.S)
_SOURCE_RE = re.compile(r"<source>(?P<s>.*?)</source>", re.S)
_TRANS_RE = re.compile(r"(?P<open><(?P<tag>translation|numerusform)\b[^>]*>)(?P<t>.*?)(?P<close></(?P=tag)>)", re.S)


def transform_ts(text: str, rel: str, found: dict[int, int]) -> tuple[str, list[str]]:
    """Rewrite the TS_RULES messages in one .ts file. ``found`` counts matches per rule."""
    notes: list[str] = []

    def fix_message(ctx_name: str, m: re.Match) -> str:
        body = m.group("body")
        sm = _SOURCE_RE.search(body)
        if not sm:
            return m.group(0)
        src = sm.group("s")
        for i, (cname, old, new, action) in enumerate(TS_RULES):
            if cname != ctx_name:
                continue
            if new is not None and src == new:
                found[i] += 1
                return m.group(0)
            if src != old:
                continue
            found[i] += 1
            if action == "drop":
                notes.append(f"drop stale {cname}: {old!r}")
                return ""
            new_body = body[: sm.start("s")] + new + body[sm.end("s"):]
            new_body = _TRANS_RE.sub(lambda t: t.group("open") + action(t.group("t")) + t.group("close"), new_body)
            msg = m.group(0).replace(body, new_body, 1)
            try:
                ET.fromstring(f"<message{m.group('attrs')}>{new_body}</message>")
            except ET.ParseError as e:
                raise RebrandError(f"{rel}: rewritten message is not valid XML ({e}): {new_body[:200]!r}")
            notes.append(f"{cname}: {old[:50]!r} -> {new!r}")
            return msg
        return m.group(0)

    def fix_context(cm: re.Match) -> str:
        name = cm.group("name")
        if name not in {r[0] for r in TS_RULES}:
            return cm.group(0)
        body = cm.group("body")
        new_body = _MESSAGE_RE.sub(lambda m: fix_message(name, m), body)
        return cm.group(0).replace(body, new_body, 1) if new_body != body else cm.group(0)

    return _CONTEXT_RE.sub(fix_context, text), notes


def step_translations(ctx: Context) -> None:
    files = sorted((ctx.root / "translations").glob("client_*.ts"))
    if not files:
        raise RebrandError("no translations/client_*.ts found")
    found = {i: 0 for i in range(len(TS_RULES))}
    for p in files:
        rel = p.relative_to(ctx.root).as_posix()
        text = ctx.read(rel)
        new_text, notes = transform_ts(text, rel, found)
        if new_text != text:
            ctx.write(rel, new_text, "; ".join(notes) or "translations")
    # Not every language file carries every message, but each rule must match
    # somewhere (at least client_en.ts); otherwise upstream changed the text.
    for i, (cname, old, new, action) in enumerate(TS_RULES):
        if action != "drop" and not found[i]:
            raise RebrandError(f"translations: message ({cname}, {old[:60]!r}) found in no file - upstream text changed? Update TS_RULES.")


