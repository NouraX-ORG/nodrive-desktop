#!/usr/bin/env python3
"""Apply the NoDrive branding to the Nextcloud desktop source tree.

Idempotent: run it as often as you like; a second run changes nothing.
Re-run it after every upstream merge (see docs/upstream-updates.md).

    python tools/rebrand.py            apply all changes
    python tools/rebrand.py --check    change nothing; exit 1 if a run would change files
    python tools/rebrand.py -v         list every change

What it does (plan: plans/desktop-plan.md, sections 1-8 and 11.4):
 1. renders nodrive/NODRIVE.cmake from tools/branding/ids.json (names, ids,
    version 35.0.0-nourax.1, fixed server, switched-off features, colours,
    theme class, NOURAX_PRIVACY_URL) and includes it from CMakeLists.txt;
 2. patches the few places that no CMake option reaches (theme link colour
    and repository link, wizard sign-up/self-host links and buttons, the
    server-entry page, the server lock, the hidden legal-notice button and
    the privacy link, three English literals, Style.qml colours, the Settings
    switch colour, SVG glyph colours, the folder-watcher probe file names);
 3. rewrites the four translatable messages that name Nextcloud in every
    translations/client_*.ts file;
 4. replaces trademarked Nextcloud glyphs with neutral upstream glyphs and
    writes the Windows tile manifest;
 5. assembles nodrive/licenses/ (licence texts + THIRD-PARTY-NOTICES.txt);
 6. small test adjustments and the NoDrive branding unit test;
 7. runs every tools/rebrand.d/*.py plugin (platform lanes) in name order.

Images are made separately by tools/make-icons.py (Pillow).
"""

