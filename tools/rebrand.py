def _q(value) -> str:
    text = str(value)
    if any(c in text for c in '"\\$;'):
        raise RebrandError(f"unsupported character in CMake value {text!r}")
    return f'"{text}"'


def render_nodrive_cmake(ids: dict) -> str:
    c = ids["cmake"]
    p = ids["product"]
    col = ids["colors"]
    sw = ids["switches"]
    win = ids["windows"]
    L = []
    a = L.append
    a("# SPDX-FileCopyrightText: 2026 Nourax")
    a("# SPDX-License-Identifier: GPL-2.0-or-later")
    a("#")
    a("# NoDrive branding overlay. GENERATED by tools/rebrand.py from")
    a("# tools/branding/ids.json - edit ids.json and re-run the tool instead.")
    a("#")
    a("# CMakeLists.txt includes this file right after NEXTCLOUD.cmake and the")
    a("# CfApi block. Plain set() creates normal variables, which shadow cache")
    a("# entries, so a -D on the command line (or from KDE Craft) cannot undo")
    a("# these product facts. New upstream options keep their defaults.")
    a("")
    a("# --- Names and ids (plan section 2) ---")
    for key in (
        "APPLICATION_NAME", "APPLICATION_SHORTNAME", "APPLICATION_EXECUTABLE",
        "APPLICATION_CONFIG_NAME", "APPLICATION_ICON_NAME", "APPLICATION_VENDOR",
        "APPLICATION_DOMAIN", "APPLICATION_REV_DOMAIN", "APPLICATION_REV_DOMAIN_DBUS",
        "APPLICATION_REV_DOMAIN_INSTALLER", "LINUX_PACKAGE_SHORTNAME", "LINUX_APPLICATION_ID",
        "APPLICATION_VIRTUALFILE_SUFFIX", "DEVELOPMENT_TEAM", "DBUS_PREFIX",
    ):
        a(f"set({key} {_q(c[key])})")
    a("# Kept on purpose: the server's web UI builds nc://open/... links (\"Open locally\").")
    a(f"set(APPLICATION_URI_HANDLER_SCHEME {_q(c['APPLICATION_URI_HANDLER_SCHEME'])})")
    a("")
    a("# --- Version: <upstream>-nourax.<n> ---")
    a(f"set(NODRIVE_RELEASE {int(p['nourax_release'])})")
    a('set(MIRALL_VERSION_SUFFIX "-nourax.${NODRIVE_RELEASE}")')
    a("")
    a("# --- Fixed server, browser sign-in (Login Flow v2) ---")
    a(f"set(APPLICATION_SERVER_URL {_q(p['server_url'])})")
    a(f"set(APPLICATION_SERVER_URL_ENFORCE {sw['APPLICATION_SERVER_URL_ENFORCE']})")
    a("")
    a("# --- Links ---")
    a("# Help link. Must never be empty: an empty value makes theme.cpp fall back")
    a("# to upstream's documentation site. Override with -DNODRIVE_HELP_URL=...")
    a(f"set(NODRIVE_HELP_URL {_q(p['help_url'])} CACHE STRING \"NoDrive help link (must not be empty)\")")
    a('set(APPLICATION_HELP_URL "${NODRIVE_HELP_URL}")')
    a("# Privacy-policy link. Empty = the link is hidden (owner to-do: real URL).")
    a(f"set(NOURAX_PRIVACY_URL {_q(p['privacy_url'])} CACHE STRING \"Nourax privacy-policy URL; empty hides the link\")")
    a("configure_file(${CMAKE_SOURCE_DIR}/nodrive/nodriveconfig.h.in ${CMAKE_BINARY_DIR}/nodrive/nodriveconfig.h)")
    a("")
    a("# --- Switched off: updater, providers list, crash reporter, account import ---")
    a(f"set(BUILD_UPDATER {sw['BUILD_UPDATER']})")
    a("# theme.cpp needs a non-empty update URL to compile; it is never contacted")
    a("# because no updater code is built (BUILD_UPDATER OFF).")
    a(f"set(APPLICATION_UPDATE_URL {_q(p['update_url_placeholder'])})")
    a(f"set(WITH_PROVIDERS {sw['WITH_PROVIDERS']})")
    a(f"set(WITH_CRASHREPORTER {sw['WITH_CRASHREPORTER']})")
    a("# Do not import or show accounts of the real Nextcloud client (side by side).")
    a(f"set(DISABLE_ACCOUNT_MIGRATION {sw['DISABLE_ACCOUNT_MIGRATION']})")
    a(f"set(APPLICATION_DISPLAY_LEGACY_IMPORT_DIALOG {sw['APPLICATION_DISPLAY_LEGACY_IMPORT_DIALOG']})")
    a("")
    a("# --- Look: Nourax colours and logo (tools/make-icons.py) ---")
    a(f"set(NEXTCLOUD_BACKGROUND_COLOR {_q(col['primary'])})")
    a(f"set(APPLICATION_WIZARD_HEADER_BACKGROUND_COLOR {_q(col['primary'])})")
    a(f"set(APPLICATION_WIZARD_HEADER_TITLE_COLOR {_q(col['wizard_header_title'])})")
    a(f"set(APPLICATION_WIZARD_USE_CUSTOM_LOGO {sw['APPLICATION_WIZARD_USE_CUSTOM_LOGO']})")
    a(f"set(APPLICATION_ICON_SET {_q(sw['APPLICATION_ICON_SET'])})")
    a("# NEXTCLOUD.cmake decided the Icon Composer path while the name was still")
    a("# Nextcloud; NoDrive uses the classic .icns made from our PNGs.")
    a(f"set(MACOS_USE_ICON_COMPOSER {sw['MACOS_USE_ICON_COMPOSER']})")
    a("")
    a("# --- Theme class (upstream hook THEME_CLASS / THEME_INCLUDE) ---")
    a(f"set(THEME_CLASS {_q(c['THEME_CLASS'])})")
    a(f"set(THEME_INCLUDE {_q(c['THEME_INCLUDE'])})")
    a("include_directories(${CMAKE_SOURCE_DIR}/nodrive ${CMAKE_BINARY_DIR}/nodrive)")
    a("")
    a("# --- Windows ids: new GUIDs so NoDrive and Nextcloud can be installed side by side ---")
    a("if(WIN32)")
    for key in (
        "WIN_SHELLEXT_CONTEXT_MENU_GUID", "WIN_SHELLEXT_OVERLAY_GUID_ERROR", "WIN_SHELLEXT_OVERLAY_GUID_OK",
        "WIN_SHELLEXT_OVERLAY_GUID_OK_SHARED", "WIN_SHELLEXT_OVERLAY_GUID_SYNC", "WIN_SHELLEXT_OVERLAY_GUID_WARNING",
        "WIN_MSI_UPGRADE_CODE",
    ):
        a(f"    set({key} {_q(win[key])})")
    a("endif()")
    a(f"set(CFAPI_SHELLEXT_APPID_REG {_q(win['CFAPI_SHELLEXT_APPID_REG'])})")
    a('set(CFAPI_SHELLEXT_APPID_DISPLAY_NAME "${APPLICATION_NAME} CfApi Shell Extensions")')
    a(f"set(CFAPI_SHELLEXT_CUSTOM_STATE_HANDLER_CLASS_ID {_q(win['CFAPI_SHELLEXT_CUSTOM_STATE_HANDLER_CLASS_ID'])})")
    a('set(CFAPI_SHELLEXT_CUSTOM_STATE_HANDLER_CLASS_ID_REG "{${CFAPI_SHELLEXT_CUSTOM_STATE_HANDLER_CLASS_ID}}")')
    a('set(CFAPI_SHELLEXT_CUSTOM_STATE_HANDLER_DISPLAY_NAME "${APPLICATION_NAME} Custom State Handler")')
    a(f"set(CFAPI_SHELLEXT_THUMBNAIL_HANDLER_CLASS_ID {_q(win['CFAPI_SHELLEXT_THUMBNAIL_HANDLER_CLASS_ID'])})")
    a('set(CFAPI_SHELLEXT_THUMBNAIL_HANDLER_CLASS_ID_REG "{${CFAPI_SHELLEXT_THUMBNAIL_HANDLER_CLASS_ID}}")')
    a('set(CFAPI_SHELLEXT_THUMBNAIL_HANDLER_DISPLAY_NAME "${APPLICATION_NAME} Thumbnail Handler")')
    a("")
    a("# --- Guards ---")
    a("if(NOT APPLICATION_HELP_URL)")
    a('    message(FATAL_ERROR "NoDrive: APPLICATION_HELP_URL must not be empty (empty falls back to the upstream documentation link)")')
    a("endif()")
    a("if(NOT APPLICATION_SERVER_URL OR NOT APPLICATION_SERVER_URL_ENFORCE)")
    a('    message(FATAL_ERROR "NoDrive: the server URL must be set and enforced")')
    a("endif()")
    a('message(STATUS "NoDrive branding: ${APPLICATION_NAME} by ${APPLICATION_VENDOR}, server ${APPLICATION_SERVER_URL}, version suffix ${MIRALL_VERSION_SUFFIX}")')
    return "\n".join(L) + "\n"


def step_overlay(ctx: Context) -> None:
    ctx.write("nodrive/NODRIVE.cmake", render_nodrive_cmake(ctx.ids), "render from ids.json")
    for rel in ("nodrive/nodrivetheme.h", "nodrive/nodriveconfig.h.in", "nodrive/brand/nourax-logo.png"):
        if not ctx.exists(rel):
            raise RebrandError(f"{rel} is missing (it is committed in the repo)")
    ctx.require("nodrive/nodrivetheme.h", "class NoDriveTheme : public Theme")
    ctx.require("nodrive/nodriveconfig.h.in", "@NOURAX_PRIVACY_URL@")
    ctx.replace(
        "CMakeLists.txt",
        'set( APPLICATION_URI_HANDLER_SCHEME "nc")\n',
        'set( APPLICATION_URI_HANDLER_SCHEME "nc")\n'
        "\n"
        "# NoDrive branding overlay. Generated values; see docs/branding.md.\n"
        "include(${CMAKE_SOURCE_DIR}/nodrive/NODRIVE.cmake)\n",
        what="include nodrive/NODRIVE.cmake",
    )
    # NextcloudCPack.cmake (included from CMakeLists.txt before add_subdirectory(src))
    # includes NEXTCLOUD.cmake a second time, which would reset every name and id
    # to Nextcloud's. Re-apply the overlay right after that second include.
    ctx.replace(
        "NextcloudCPack.cmake",
        'include("${CMAKE_SOURCE_DIR}/NEXTCLOUD.cmake")\n',
        'include("${CMAKE_SOURCE_DIR}/NEXTCLOUD.cmake")\n'
        "# NoDrive: the line above resets the names to upstream's; apply the overlay again.\n"
        'include("${CMAKE_SOURCE_DIR}/nodrive/NODRIVE.cmake")\n',
        what="re-apply nodrive/NODRIVE.cmake after the CPack include of NEXTCLOUD.cmake",
    )


